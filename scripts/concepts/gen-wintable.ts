// Writes src/game/winTable.ts: hole score odds (to par, −2..+7) by handicap (0, 4 … 40) and par,
// from the balance golf model. Rerun if scripts/balance/golf.ts changes: npx tsx scripts/concepts/gen-wintable.ts
import { writeFileSync } from 'node:fs';
import { makeHole, mulberry32, playHole, skill } from '../balance/golf';
const rng = mulberry32(2026);
const HCPS = Array.from({ length: 11 }, (_, i) => i * 4);
const N = 40000;
const rows = HCPS.map((h) =>
  [3, 4, 5].map((par) => {
    const bins = new Array(10).fill(0); // −2..+7
    for (let i = 0; i < N; i++) {
      const tp = playHole(skill(h), makeHole(par, rng), rng, rng() < 0.22).strokes - par;
      bins[Math.max(0, Math.min(9, tp + 2))]++;
    }
    // per mille, adjusted so each row sums to exactly 1000
    const pm = bins.map((b) => Math.round((1000 * b) / N));
    pm[pm.indexOf(Math.max(...pm))] += 1000 - pm.reduce((a, b) => a + b, 0);
    return pm;
  }),
);
const body = `// Generated by scripts/concepts/gen-wintable.ts from the balance golf model. Don't edit by hand.
// HOLE_ODDS[h][par - 3][k]: chance (per 1000) that a golfer of handicap WIN_HCPS[h] scores k − 2 to par.
export const WIN_HCPS = ${JSON.stringify(HCPS)} as const;
export const HOLE_ODDS: readonly (readonly (readonly number[])[])[] = ${JSON.stringify(rows)};
`;
writeFileSync(new URL('../../src/game/winTable.ts', import.meta.url), body);
console.log('wrote winTable.ts', rows[5][1]);
